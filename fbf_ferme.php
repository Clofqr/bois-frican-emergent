    <strong>Une ferme en pleine évolution</strong><br>
    Tout a commencé avec l’arrivée des vaches, puis sont venus les premiers veaux, marquant le début d’une belle dynamique. <br>
    Les poneys ont ensuite rejoint la ferme pour proposer des activités autour du cheval, suivis par les taureaux pour compléter le troupeau. <br>
    Aujourd’hui, nous prévoyons d’agrandir notre troupeau de poneys afin d’accueillir plus d’enfants et de familles autour d’activités équestres variées et accessibles à tous.
  </p>
