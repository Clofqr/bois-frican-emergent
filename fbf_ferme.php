<h2>La vie à la ferme</h2>

 <div class="ferme-wrapper">
    <div class="ferme-title">     
      <h3><u>Un cadre naturel préservé</u></h3><br>
   <p class="text-ferme1" style="color: #333; font-size: 16px; line-height: 1.6;">       
    La Ferme du Bois Frican se trouve dans une grande maison en pierre, tout près d’une rivière et de la voie verte. <br>
    Haies bocagères, chemins creux et prés l’entourent, offrant un cadre paisible et typique de la région.<br>
    Elle est située dans le bocage ornais, à deux pas de Domfront, à 20 km de Bagnoles-de-l’Orne et 35 km de Flers.
   </p>
